const $ = (id) => document.getElementById(id);
const form = $('autoForm');
const cfg = AUTO[form.dataset.ind];

$('au-type').innerHTML = Object.entries(cfg.types).map(([k, t]) => `<option value="${k}">${t.label}</option>`).join('');
$('au-item-label').firstChild.textContent = cfg.item;
$('au-item').value = cfg.itemDefault;

function buildAuto() {
  const c = {
    company: $('au-company').value.trim() || 'みほん',
    staff: $('au-staff').value.trim() || '担当',
    item: $('au-item').value.trim() || cfg.itemDefault,
  };
  const t = cfg.types[$('au-type').value];
  const soft = $('au-tone').value === 'soft';
  const end = soft ? 'どうぞよろしくお願いします。' : '何とぞよろしくお願いいたします。';

  const first = [
    soft ? `お問い合わせありがとうございます！${c.company}です。` : `このたびはお問い合わせいただき、誠にありがとうございます。${c.company}でございます。`,
    `「${c.item}」${t.ask}、承りました。`,
    '担当から改めてご連絡します。その前に、次のことを教えていただけますか。',
    '',
    ...t.q.map((x, i) => `${'①②③④'[i]} ${x}`),
    '',
    soft ? 'わかる範囲で大丈夫です！' : 'お分かりになる範囲で構いません。',
  ].join('\n');

  const reply = [
    '〇〇様',
    '',
    soft ? `${c.company}の${c.staff}です。教えていただき、ありがとうございます！` : `${c.company}の${c.staff}でございます。ご回答いただき、ありがとうございます。`,
    '',
    t.reply,
    '',
    end,
  ].join('\n');

  return [
    { title: '① 届いたその場で、自動で返る一次返信', text: first },
    { title: '② お客様の答えがそろったあとの返信文（下書き）', text: reply },
    ...cfg.follow.map(([when, f]) => ({ title: `③ 追客｜${when}に自動で送る`, text: f(c) })),
  ];
}

form.addEventListener('submit', (e) => {
  e.preventDefault();
  renderOutputs($('autoOut'), buildAuto());
});
form.requestSubmit();
